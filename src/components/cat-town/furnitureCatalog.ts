// Helper lấy URL ảnh của món đồ nội thất (chỉ trả về asset thật đã cắt, TUYỆT ĐỐI không fallback lung tung sang bed_01)
export function getFurnitureAssetUrl(itemId: string, fallbackUrl?: string): string {
  if (fallbackUrl && (fallbackUrl.startsWith('/assets/furniture/') || fallbackUrl.startsWith('http://') || fallbackUrl.startsWith('https://'))) {
    return fallbackUrl;
  }

  const found = DEFAULT_FURNITURE_CATALOG.find((f) => f.id === itemId);
  if (found?.imageUrl) return found.imageUrl;

  // Pattern matching by ID prefix (bed_01..16, sofa_01..06, wall_01..15, floor_01..15, decor_01..104)
  if (/^bed_\d+$/.test(itemId)) return `/assets/furniture/beds/${itemId}.png`;
  if (/^sofa_\d+$/.test(itemId)) return `/assets/furniture/sofas/${itemId}.png`;
  if (/^wall_\d+$/.test(itemId)) return `/assets/furniture/wallpapers/${itemId}.png`;
  if (/^floor_\d+$/.test(itemId)) return `/assets/furniture/floors/${itemId}.png`;
  if (/^decor_\d+$/.test(itemId)) return `/assets/furniture/decor/${itemId}.png`;

  // KHÔNG fallback về bed_01.png để tránh việc món nào cũng bị biến thành giường nệm rơm vàng
  return fallbackUrl || '';
}

// Lấy danh sách item theo category và tự động sắp xếp theo giá tăng dần
// CHỈ GIỮ LẠI những món có hình ảnh thật sự hợp lệ, xóa bỏ hoàn toàn món ma/món thiếu ảnh
export function getCatalogByCategory(
  catalog: CatTownFurniture[],
  category: 'bed' | 'sofa' | 'wallpaper' | 'floor' | 'decor'
): CatTownFurniture[] {
  return (catalog || [])
    .filter((item) => {
      if (item.isHidden) return false;

      // Kiểm tra món có file ảnh thực sự không (loại bỏ các id cũ như furn_cat_tree, furn_fish_sofa, furn_wall_strawberry)
      const assetUrl = item.imageUrl || getFurnitureAssetUrl(item.id);
      if (!assetUrl || (!assetUrl.startsWith('/assets/furniture/') && !assetUrl.startsWith('http://') && !assetUrl.startsWith('https://'))) {
        return false;
      }

      if (category === 'bed') return item.category === 'bed' || item.id.startsWith('bed_');
      if (category === 'sofa') return item.category === 'sofa' || item.id.startsWith('sofa_');
      if (category === 'wallpaper') return item.category === 'wallpaper' || item.id.startsWith('wall_');
      if (category === 'floor') return item.category === 'floor' || item.id.startsWith('floor_');
      if (category === 'decor') {
        return (
          item.id.startsWith('decor_') ||
          item.category === 'decor' ||
          item.category === 'furniture' ||
          item.category === 'cat_item' ||
          item.category === 'plant' ||
          item.category === 'toy'
        );
      }
      return false;
    })
    .sort((a, b) => a.price - b.price);
}
